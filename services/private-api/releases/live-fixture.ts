import assert from 'node:assert/strict';
import { generateKeyPairSync, randomUUID, verify } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { Pool } from 'pg';
import Fastify from 'fastify';
import { SessionStore } from '../../../packages/contracts/auth/store.js';
import { hashPassword } from '../../../packages/contracts/auth/crypto.js';
import { canonicalize } from '../../../packages/contracts/hash.js';
import { PrivateIntentStore } from '../db/intent-store.js';
import { installPrivateAuth } from '../auth/routes.js';
import { PrivateReleaseStore } from './store.js';
import { installReleaseRoutes } from './routes.js';
import { projectPublicListing } from '../../../packages/contracts/public/task.js';
import { singleUnitContract } from '../../../tests/contracts/fixtures.js';
import { ApprovedReleaseCompiler } from './compiler.js';
import { installCompilationRoutes } from './compiler-routes.js';
import { preparePublicWorkspace } from '../../../packages/compiler/workspace.js';
import { PUBLIC_IMAGE_PROFILE } from '../../../templates/workspaces/public-image-profile.js';
import { byteHash } from '../../../packages/contracts/hash.js';

export async function runReleaseFixture(migrations: string[], schemaSql: string) {
  assert.equal(process.env.SYNTHETIC_RELEASE_FIXTURE, 'synthetic-fixture');
  assert.equal(process.env.PRIVATE_DATABASE_NAME, 'private_task');
  const configuration = { host: process.env.PRIVATE_DATABASE_HOST, user: process.env.PRIVATE_DATABASE_USER, password: readFileSync(process.env.PRIVATE_DATABASE_PASSWORD_FILE!, 'utf8').trim(), max: 3 };
  const admin = new Pool({ ...configuration, database: 'private_task' });
  const database = `synthetic_release_${randomUUID().replaceAll('-', '')}`;
  assert.match(database, /^synthetic_release_[a-f0-9]{32}$/);
  await admin.query(`CREATE DATABASE "${database}"`);
  await admin.end();
  const pool = new Pool({ ...configuration, database });
  const app = Fastify({ logger: false });
  try {
    for (const migration of migrations) await pool.query(migration);
    await pool.query(schemaSql);
    const sessions = new SessionStore(pool, 'private', Buffer.alloc(32, 7));
    const password = 'synthetic-release-fixture-password', passwordHash = await hashPassword(password);
    const users = [];
    for (const role of ['owner', 'requester', 'operator'] as const) {
      const id = randomUUID(), username = `synthetic.release.${role}.${id.slice(0,8)}`;
      await pool.query('INSERT INTO private_accounts (id,username,password_hash,role) VALUES ($1,$2,$3,$4)', [id,username,passwordHash,role]);
      const login = await sessions.login(username, password);
      users.push({ actor: await sessions.authenticateMutation(login.cookie, login.csrfToken), login });
    }
    const owner = users[0]!, requester = users[1]!, operator = users[2]!;
    const intents = new PrivateIntentStore(pool);
    const intent = { schemaVersion: 1, intentId: randomUUID(), version: 1, goal: 'Synthetic release fixture', snapshotHash: 'a'.repeat(64), state: 'draft', facts: [], evidence: [], decisions: [], assumptions: [], unknowns: [], acceptanceExamples: [], scope: { included: ['Synthetic only'], excluded: ['Real customer data'] } };
    await intents.create(owner.actor, intent);
    await intents.transition(owner.actor, intent.intentId, 1, 'ready_for_approval');
    const current = await intents.read(owner.actor, intent.intentId);
    await intents.transition(owner.actor, intent.intentId, 1, 'approved', current.contentHash);
    const keys = generateKeyPairSync('ed25519'), store = new PrivateReleaseStore(pool, keys.privateKey);
    const compiled = new ApprovedReleaseCompiler(pool, keys.publicKey);
    const contract = singleUnitContract(); contract.taskId = randomUUID(); contract.lineageId = randomUUID();
    const candidate = { contract, listing: projectPublicListing(contract, 30), assets: [{ path: 'src/PlanSelector.tsx', sourceAssetId: randomUUID(), mediaType: 'application/typescript', contentBase64: Buffer.from('export const synthetic = true;\n').toString('base64') }], feedbackPolicy: { schemaVersion: 1, id: contract.feedbackPolicyId, categories: ['received', 'processing', 'owner_review', 'accepted', 'changes_required', 'package_defect', 'infrastructure_issue', 'expired'], messageCodes: ['requirement_not_met', 'invalid_input', 'check_unavailable', 'passed'], privateDiagnostics: 'none', publicDetails: 'approved_public_checks_only' } };
    const input = { intentId: intent.intentId, intentVersion: 1, approvedIntentHash: current.contentHash, privateRevision: 'b'.repeat(64), candidate };
    const handlers = installPrivateAuth(app, sessions, 'localhost_demo');
    installReleaseRoutes(app, handlers, store);
    installCompilationRoutes(app, handlers, compiled);
    const headers = { origin: 'http://private.localhost:3000', cookie: `private_session=${owner.login.cookie}`, 'x-csrf-token': owner.login.csrfToken };
    assert.equal((await app.inject({ method: 'POST', url: '/v1/release-candidates', headers: { ...headers, 'x-csrf-token': 'wrong' }, payload: input })).statusCode, 401);
    const stagedResponse = await app.inject({ method: 'POST', url: '/v1/release-candidates', headers, payload: input });
    assert.equal(stagedResponse.statusCode, 201);
    assert.equal((await app.inject({ method: 'POST', url: '/v1/release-candidates', headers, payload: input })).statusCode, 409);
    const staged = stagedResponse.json();
    assert.equal(staged.approval, null);
    const approval = { expectedVersion: 1, manifestHash: staged.manifestHash, combinedDisclosureReviewed: true, semanticDisclosureRationale: 'Entirely synthetic disclosure reviewed in this test.' };
    for (const user of [requester, operator]) {
      const denied = await app.inject({ method: 'POST', url: `/v1/release-candidates/${staged.id}/approval`, headers: { origin: headers.origin, cookie: `private_session=${user.login.cookie}`, 'x-csrf-token': user.login.csrfToken }, payload: approval });
      assert.equal(denied.statusCode, 403);
    }
    const wrongHash = await app.inject({ method: 'POST', url: `/v1/release-candidates/${staged.id}/approval`, headers, payload: { ...approval, manifestHash: 'f'.repeat(64) } });
    assert.equal(wrongHash.statusCode, 409);
    const approve = () => app.inject({ method: 'POST', url: `/v1/release-candidates/${staged.id}/approval`, headers, payload: approval });
    const concurrent = await Promise.all([approve(), approve()]);
    assert.deepEqual(concurrent.map(result => result.statusCode).sort(), [200,409]);
    const approved = concurrent.find(result => result.statusCode === 200)!.json();
    assert.equal(verify(null, Buffer.from(canonicalize(staged.manifest)), keys.publicKey, Buffer.from(approved.signature, 'base64')), true);
    assert.equal((await pool.query('SELECT count(*)::int AS count FROM private_release_approvals WHERE id=$1', [staged.id])).rows[0].count, 1);
    const object = (await pool.query('SELECT payload FROM private_release_objects WHERE sha256=$1', [staged.assets[0].sha256])).rows[0];
    assert.equal(object.payload.toString('base64'), candidate.assets[0]!.contentBase64);
    await assert.rejects(pool.query('UPDATE private_release_objects SET payload=payload WHERE sha256=$1', [staged.assets[0].sha256]));
    await assert.rejects(pool.query('UPDATE private_release_candidates SET candidate=$2 WHERE id=$1', [staged.id,{ ...candidate, listing: { ...candidate.listing, title: 'Unreviewed' } }]));
    await assert.rejects(pool.query("UPDATE private_release_signatures SET semantic_rationale='changed' WHERE approval_id=$1", [staged.id]));
    await assert.rejects(pool.query("UPDATE private_release_candidates SET state='release_review' WHERE id=$1", [staged.id]));
    await assert.rejects(compiled.compile(owner.actor, staged.id, { expectedVersion: 2, manifestHash: staged.manifestHash }), /invalid_approved_workspace/);
    const workspaceContract = structuredClone(contract); workspaceContract.taskId = randomUUID();
    const workspace = preparePublicWorkspace(workspaceContract, { imageDigest: PUBLIC_IMAGE_PROFILE.imageDigest });
    const workspaceCandidate = { contract: workspace.contract, listing: projectPublicListing(workspace.contract, 30), feedbackPolicy: candidate.feedbackPolicy, assets: workspace.assets.map(asset => ({ ...asset, sourceAssetId: randomUUID() })) };
    const workspaceReview = await store.stage(owner.actor, { ...input, candidate: workspaceCandidate });
    await assert.rejects(compiled.compile(owner.actor, workspaceReview.id, { expectedVersion: 1, manifestHash: workspaceReview.manifestHash }), /missing_evidence/);
    await store.approve(owner.actor, workspaceReview.id, { ...approval, manifestHash: workspaceReview.manifestHash });
    const artifact = await compiled.compile(owner.actor, workspaceReview.id, { expectedVersion: 2, manifestHash: workspaceReview.manifestHash });
    assert.equal(artifact.sha256, byteHash(artifact.bytes));
    assert.equal(artifact.runtimeReadiness, 'unverified');
    const replay = await compiled.compile(owner.actor, workspaceReview.id, { expectedVersion: 2, manifestHash: workspaceReview.manifestHash });
    assert.equal(replay.sha256, artifact.sha256);
    const packageResponse = await app.inject({ method: 'POST', url: `/v1/release-candidates/${workspaceReview.id}/package`, headers, payload: { expectedVersion: 2, manifestHash: workspaceReview.manifestHash } });
    assert.equal(packageResponse.statusCode, 200);
    assert.equal(packageResponse.headers['content-type'], 'application/zip');
    assert.equal(packageResponse.headers['x-package-sha256'], byteHash(packageResponse.rawPayload));
    assert.equal(packageResponse.headers['x-runtime-readiness'], 'unverified');
    await assert.rejects(compiled.compile(requester.actor, workspaceReview.id, { expectedVersion: 2, manifestHash: workspaceReview.manifestHash }), /forbidden_role/);
    const nextCandidate = structuredClone(candidate); nextCandidate.contract.taskId = randomUUID(); nextCandidate.listing.taskId = nextCandidate.contract.taskId;
    const next = await store.stage(owner.actor, { ...input, candidate: nextCandidate });
    await intents.revise(owner.actor, { ...intent, version: 2, goal: 'Changed synthetic outcome' }, 1);
    await assert.rejects(store.approve(owner.actor, next.id, { ...approval, manifestHash: next.manifestHash }), /missing_evidence/);
    await assert.rejects(compiled.compile(owner.actor, workspaceReview.id, { expectedVersion: 2, manifestHash: workspaceReview.manifestHash }), /missing_evidence/);
    await sessions.revokeSession(owner.actor);
    await assert.rejects(store.review(owner.actor, staged.id), /forbidden_role/);
    await assert.rejects(compiled.compile(owner.actor, workspaceReview.id, { expectedVersion: 2, manifestHash: workspaceReview.manifestHash }), /forbidden_role/);
    await assert.rejects(store.approve(owner.actor, next.id, { ...approval, manifestHash: next.manifestHash }), /forbidden_role/);
    return { assurance: 'tested', realCustomerData: false, scope: 'Actual synthetic PostgreSQL and authenticated injected HTTP; not real runner or independent review.', database, immutableAssets: 'tested', ownerSession: 'tested', csrf: 'tested', roleDenial: 'tested', approvalConcurrency: 'tested', staleIntent: 'tested', signature: 'tested', integratedRuntime: 'separate_browser_evidence' };
  } finally { await app.close(); await pool.end(); }
}
