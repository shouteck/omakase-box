import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SKILL_TEXT } from '../packages/box-bounty/wording.ts';

const target = new URL('../docs/box-v4/launch/skill-repo/skills/omakase-box/SKILL.md', import.meta.url);
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && !['--check', '--write'].includes(args[0]))) {
  console.error('usage: node scripts/launch-skill.mjs [--write|--check]');
  process.exit(2);
}
try {
  if (args[0] === '--check') {
    if (!readFileSync(target).equals(Buffer.from(SKILL_TEXT))) throw new Error('skill draft differs from SKILL_TEXT; regenerate with --write');
    console.log('launch skill: generated bytes match SKILL_TEXT');
  } else {
    mkdirSync(new URL('.', target), { recursive: true });
    writeFileSync(target, SKILL_TEXT);
    console.log(`launch skill: wrote ${fileURLToPath(target)}`);
  }
} catch (error) {
  console.error(`launch skill: ${error.message}`);
  process.exit(1);
}
