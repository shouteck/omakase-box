import assert from 'node:assert/strict';
import { readFile, writeFile, rename } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../../..');
const path = resolve(root, '.execution/state.json');
const before = await readFile(path, 'utf8');
const state = JSON.parse(before);
const task = state.tasks['M2.3'];
assert.equal(task.status, 'done');
assert.ok(Object.values(state.tasks).every(item => !item.lease));
task.previousUiAccepted = { revision: task.revision, reviewer: task.reviewer, handoff: task.handoff, independentReviewStatus: task.independentReviewStatus, reviewReports: task.reviewReports };
state.coordinator = 'devin-coordinator-sequential';
state.reviewMode = 'sequential_fallback';
state.independentReviewVerified = false;
state.projectStatus = 'in_progress';
state.lastUpdatedAt = new Date().toISOString();
state.currentTask = 'M2.3';
state.currentTasks = ['M2.3'];
state.milestones.M2 = 'running';
task.status = 'running'; task.implementationStatus = 'running'; task.independentReviewStatus = 'not_available'; task.reviewer = null;
task.owner = state.coordinator; task.attempt += 1;
task.lease = { owner: state.coordinator, startedAt: state.lastUpdatedAt, mode: 'sequential', scope: 'User-approved intent-review UX simplification only.' };
state.nextWork = { resumeCurrentTask: 'M2.3', reason: 'Simplify approved demo UI; exact-revision review must be renewed after product edits. Real-runner gates remain blocked.' };
state.delivery.independentReview = 'partial';
assert.equal(await readFile(path, 'utf8'), before);
await writeFile(path + '.tmp', JSON.stringify(state, null, 2) + '\n', { flag: 'wx' });
await rename(path + '.tmp', path);
console.log(JSON.stringify({ taskId: 'M2.3', status: 'running', independentReviewStatus: 'not_available', scope: task.lease.scope }));
