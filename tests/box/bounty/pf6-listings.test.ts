import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { BOUNTY_COMMANDS, SETUP_USAGE, SKILL_TEXT } from '../../../packages/box-bounty/index.js';
import { ROOT } from './support.js';

const base = 'docs/box-v4/launch/';
const read = (path: string): string => readFileSync(join(ROOT, base, path), 'utf8');
const commands = (text: string): string[] => [...text.matchAll(/(?<![\w/-])omakase-box[ \t]+([a-z][a-z-]*)/g)].map(match => match[1]!);
const known = new Set([...Object.keys(BOUNTY_COMMANDS), ...commands(SETUP_USAGE[0]!)]);
const promises = /\b(?:must|waiting)\b|\bguarantee(?:d|s)? (?:income|payment|rewards?|earnings)|\b(?:earn|make) (?:easy|guaranteed) money|\bget rich\b|\bpassive income\b|\bswarm\b|\bsoftware factory\b/i;
const currentControl = /humans approve listings and payments/i;
const staleBoard = /open-bounty-board\.box-platform\.workers\.dev/;
const autonomyNow = /no human involvement|without (?:any )?humans?\b|end to end with no human/i;
const listing = read('listings/LISTINGS.md');
const copies = [...listing.matchAll(/```(?:text|markdown)\n([\s\S]*?)\n```/g)].map(match => match[1]!);
const checkCopy = (text: string): void => {
  expect(text.trim().length).toBeGreaterThan(0);
  expect(text).not.toMatch(promises);
  expect(text).toMatch(currentControl);
  expect(text).not.toMatch(autonomyNow);
  expect(text).not.toMatch(staleBoard);
  expect(commands(text).filter(command => !known.has(command))).toEqual([]);
  const skill = /\bskill\b/i.exec(text)?.index;
  const cli = /\bCLI\b/.exec(text)?.index;
  const mcp = /\bMCP\b/.exec(text)?.index;
  if (skill !== undefined && cli !== undefined && mcp !== undefined) {
    expect(skill).toBeLessThan(cli);
    expect(cli).toBeLessThan(mcp);
  }
};

describe('PF6 listing drafts', () => {
  it('ships generated skill bytes without changing the approved source', () => {
    expect(readFileSync(join(ROOT, base, 'skill-repo/skills/omakase-box/SKILL.md'))).toEqual(Buffer.from(SKILL_TEXT));
    const run = spawnSync(process.execPath, ['scripts/launch-skill.mjs', '--check'], { cwd: ROOT, encoding: 'utf8' });
    expect(run.status, run.stderr).toBe(0);
    expect(run.stdout).toContain('generated bytes match SKILL_TEXT');
  });
  it('the generator refuses unknown arguments without writing', () => {
    const run = spawnSync(process.execPath, ['scripts/launch-skill.mjs', '--unknown'], { cwd: ROOT, encoding: 'utf8' });
    expect(run.status).toBe(2);
    expect(run.stderr).toContain('usage:');
    expect(read('skill-repo/skills/omakase-box/SKILL.md')).toBe(SKILL_TEXT);
  });
  it('the plugin draft shares the CLI release version', () => {
    const cli = JSON.parse(readFileSync(join(ROOT, 'packages/box-cli/package.json'), 'utf8'));
    const plugin = JSON.parse(read('skill-repo/.claude-plugin/plugin.json'));
    expect(plugin.version).toBe(cli.version);
  });
  it('the marketplace resolves its plugin and skill from the proposed repository root', () => {
    const marketplace = JSON.parse(read('skill-repo/.claude-plugin/marketplace.json'));
    const plugin = JSON.parse(read('skill-repo/.claude-plugin/plugin.json'));
    expect(marketplace.name).toBe('omakase-skills');
    expect(marketplace.owner.name).toBe('shouteck');
    expect(marketplace.plugins).toHaveLength(1);
    expect(marketplace.plugins[0]).toMatchObject({ name: plugin.name, source: '.' });
    expect(plugin.name).toBe('omakase-box');
    expect(plugin.skills).toEqual(['./skills/']);
    expect(existsSync(join(ROOT, base, 'skill-repo', marketplace.plugins[0].source, plugin.skills[0], plugin.name, 'SKILL.md'))).toBe(true);
    checkCopy(marketplace.description);
    checkCopy(marketplace.plugins[0].description);
    checkCopy(plugin.description);
  });
  it('every channel has fit, intent, paste copy and numbered owner steps', () => {
    const sections = listing.split(/^## /m).slice(1).filter(section => !section.startsWith('Proposed for') && !section.startsWith('Owner-only'));
    expect(sections).toHaveLength(11);
    for (const section of sections) {
      expect(section).toMatch(/Fit: (?:fits|optional|does not fit)/);
      expect(section).toContain('FORMATS.md');
      expect(section).toContain('Intent:');
      expect(section).toMatch(/```text\nTitle: .+\nShort: .+\nLong: .+/);
      expect(section).toMatch(/^1\. /m);
    }
    expect(copies.length).toBeGreaterThanOrEqual(12);
  });
  it.each(copies.map((copy, index) => [index + 1, copy] as const))('paste block %s uses known commands and the approved hierarchy without promises', (_index, copy) => checkCopy(copy));
  it('the README stays within five lines and covers both needs', () => {
    const text = read('skill-repo/README.md');
    expect(text.trimEnd().split('\n').length).toBeLessThanOrEqual(5);
    expect(text).toContain('npx skills add shouteck/omakase-skills');
    expect(text).toContain('https://omakasebox.dev');
    expect(text).toContain('Hand off work');
    expect(text).toContain('Find paid work');
    checkCopy(text);
  });
  it('guards catch empty copy, unknown commands, forbidden promises and reversed layers', () => {
    const ok = 'Agent Skill, CLI, MCP. Find paid work; hand off work. Humans approve listings and payments.';
    for (const text of ['', 'omakase-box invented', 'guaranteed income', 'MCP then CLI then Agent Skill. Humans approve listings and payments.', 'Agent Skill, CLI, MCP. Find paid work.', `${ok} Agents settle work end to end with no human involvement.`]) expect(() => checkCopy(text)).toThrow();
    expect(() => checkCopy(ok)).not.toThrow();
  });
});
